#!/usr/bin/env python3
"""Generate src/wide_art.c from the 16:9 artwork (428 x 200 title, 428 x 40 HUD).

The output holds only what is new: the two 54-px side strips and the centre pixels that differ from the
original picture (title = DAT entry 2, HUD frame = IMG entry 12), as palette indices.  The original pictures
come from the player's HOCUS.DAT at run time, so the repository carries no game artwork.

usage: gen_wide_art.py HOCUS.EXE HOCUS.DAT title.png hud.png > src/wide_art.c
  title.png: indexed, with the palette of DAT entry 2 (indices are used as they are)
  hud.png:   any colour mode; each colour is mapped to the nearest of the game palette's colours 0..127 (DAT 7)
"""
import sys, io, struct, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
from hocus_dat import HocusData
from PIL import Image

W, SIDE = 428, 54

def main():
    exe, dat, title_png, hud_png = sys.argv[1:5]
    H = HocusData(exe, dat)
    # originals
    pcx = Image.open(io.BytesIO(H.get(2)))
    orig_title = [[pcx.getpixel((x, y)) for x in range(320)] for y in range(200)]
    i12 = H.get(12); w4, h = struct.unpack_from('<HH', i12); d = i12[4:]
    orig_hud = [[d[(x & 3) * w4 * h + y * w4 + (x >> 2)] for x in range(320)] for y in range(40)]
    pal6 = H.get(7)
    pal = [tuple((pal6[i * 3 + k] << 2) | (pal6[i * 3 + k] >> 4) for k in range(3)) for i in range(128)]

    t = Image.open(title_png)
    assert t.size == (W, 200) and t.mode == 'P', 'title: 428 x 200, indexed'
    assert t.getpalette()[:768] == pcx.getpalette()[:768], 'title: palette must be the one of DAT entry 2'
    title = [[t.getpixel((x, y)) for x in range(W)] for y in range(200)]
    tp = pcx.getpalette()[:768]; tpal = [tuple(tp[i * 3:i * 3 + 3]) for i in range(256)]

    hm = Image.open(hud_png).convert('RGB')
    assert hm.size == (W, 40), 'hud: 428 x 40'
    cache = {}
    def nearest(c):
        if c not in cache:
            cache[c] = min(range(128), key=lambda i: sum((a - b) ** 2 for a, b in zip(pal[i], c)))
        return cache[c]
    hud = [[nearest(hm.getpixel((x, y))) for x in range(W)] for y in range(40)]

    out = sys.stdout
    out.write('/* wide_art.c - GENERATED by tools/gen_wide_art.py from the 16:9 artwork; do not edit.\n'
              ' * Only the new parts: the 54-px side strips and the centre pixels that differ from the original\n'
              ' * pictures (DAT entry 2 title, IMG entry 12 HUD frame), as palette indices. */\n'
              '#include "wide_art.h"\n\n')
    for name, img, orig, rows in (('title', title, orig_title, 200), ('hud', hud, orig_hud, 40)):
        out.write(f'const uint8_t g_wide_{name}_side[2][{rows}][{SIDE}] = {{\n')
        for side, x0 in ((0, 0), (1, SIDE + 320)):
            out.write('  {\n')
            for y in range(rows):
                out.write('    {' + ','.join(str(img[y][x0 + x]) for x in range(SIDE)) + '},\n')
            out.write('  },\n')
        out.write('};\n')
        rgb = tpal if name == 'title' else pal                     # same colour = not a change (duplicate indices)
        delta = [(x, y, img[y][x + SIDE]) for y in range(rows) for x in range(320)
                 if rgb[img[y][x + SIDE]] != rgb[orig[y][x]]]
        out.write(f'const int g_wide_{name}_ndelta = {len(delta)};\n')
        out.write(f'const WideDelta g_wide_{name}_delta[{max(1, len(delta))}] = {{\n')
        for i in range(0, len(delta), 8):
            out.write('  ' + ' '.join('{%d,%d,%d},' % p for p in delta[i:i + 8]) + '\n')
        if not delta: out.write('  {0,0,0}\n')
        out.write('};\n\n')
        print(f'{name}: {len(delta)} centre pixels differ from the original', file=sys.stderr)

if __name__ == '__main__':
    main()
