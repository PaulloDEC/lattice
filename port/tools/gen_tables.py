#!/usr/bin/env python3
"""Generate src/dat_tables.c from HOCUS.EXE: the HOCUS.DAT file table and the per-level lookup tables of the data segment.
usage: gen_tables.py HOCUS.EXE > src/dat_tables.c"""
import struct, sys
exe = open(sys.argv[1], 'rb').read()
DS0 = 0x1F110
def words(off, n, fmt='<h'): return list(struct.unpack_from('<%dh' % n if fmt == '<h' else '<%dH' % n, exe, DS0 + off))
fat = [struct.unpack_from('<II', exe, 0x1F1A4 + 8 * i) for i in range(652)]
def arr(name, vals, typ='int16_t', per=10):
    s = f'const {typ} {name}[{len(vals)}] = {{\n'
    for i in range(0, len(vals), per): s += '    ' + ', '.join(str(v) for v in vals[i:i + per]) + ',\n'
    return s + '};\n'
out = ['/* generated by tools/gen_tables.py from HOCUS.EXE (registered v1.1) - do not edit */', '#include "dat.h"', '']
out.append('const uint32_t g_dat_fat[DAT_ENTRIES][2] = {\n' + ''.join(f'    {{{o}u, {s}u}},\n' for o, s in fat) + '};\n')
out.append('/* DS:2A1A  map entry base per level: episode * 10 + level (the map files are entries base + 131 + 36 * type) */')
out.append(arr('g_lvl_map_base', words(0x2A1A, 40)))
out.append('/* DS:29CA  tileset PCX number (entry 105 + n) */'); out.append(arr('g_lvl_tileset', words(0x29CA, 40)))
out.append('/* DS:2A6A  backdrop number (PCX entry 89 + n, palette entry 73 + n) */'); out.append(arr('g_lvl_backdrop', words(0x2A6A, 40)))
out.append('/* DS:2ACE  music track per level: episode * 9 + level */'); out.append(arr('g_lvl_music', words(0x2ACE, 36)))
out.append('/* DS:2B16  lift platform tile ids per level (episode * 10 + level): {DS:CF4C, DS:CF4A} */')
out.append(arr('g_lvl_plat_tiles', words(0x2B16, 80), per=8))
out.append('/* DS:14F8  ticks per frame of the level loop (indexed by DS:790E) */'); out.append(arr('g_tick_table', words(0x14F8, 4), 'uint16_t', 4))
out.append('/* DS:2BB6 / 2BBE / 2BC6 / 2BCE  final boss start: column, row, map cell, facing */'); out.append(arr('g_boss_init', words(0x2BB6, 1) + words(0x2BBE, 1) + words(0x2BC6, 1) + words(0x2BCE, 1), per=4))
sys.stdout.write('\n'.join(out))
